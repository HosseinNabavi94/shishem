export function getAllPosts(): Post[] {
  return posts;
}

export function getPostBySlug(slug: string): Post | undefined {
  return posts.find((p) => p.slug === slug);
}

/** Teaser row on the home page. */
export function getTeaserPosts(): Post[] {
  return posts.slice(0, 3);
}

/** Sidebar list on a single post, excluding the post being read. */
export function getLatestPosts(excludeSlug?: string, count = 4): Post[] {
  return posts.filter((p) => p.slug !== excludeSlug).slice(0, count);
}
